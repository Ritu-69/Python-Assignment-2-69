# Sample list and string
fruits = ["apple", "banana", "cherry"]
word = "Python"

# Demonstrating 'in' operator
print("apple" in fruits)       # Output: True
print("mango" in fruits)       # Output: False
print("P" in word)             # Output: True

# Demonstrating 'not in' operator
print("mango" not in fruits)   # Output: True
print("banana" not in fruits)  # Output: False
print("z" not in word)         # Output: True
