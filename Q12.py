# Define two boolean variables
a = True
b = False

# 1. Logical AND: Returns True if BOTH statements are true
print("a and b is:", a and b)  # Output: False

# 2. Logical OR: Returns True if AT LEAST ONE statement is true
print("a or b is:", a or b)    # Output: True

# 3. Logical NOT: Reverses the result (True becomes False, False becomes True)
print("not a is:", not a)      # Output: False
print("not b is:", not b)      # Output: True
