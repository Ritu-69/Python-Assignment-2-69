# Define two numbers
a = 17
b = 5

# Floor division (returns the integer quotient)
floor_div = a // b

# Modulus (returns the remainder)
modulus = a % b

# Display the results
print(f"Numbers: a = {a}, b = {b}")
print(f"Floor Division ({a} // {b}): {floor_div}")
print(f"Modulus ({a} % {b}): {modulus}")
