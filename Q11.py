# Input two numbers from the user
num1 = float(input("Enter the first number: "))
num2 = float(input("Enter the second number: "))

# Compare using all relational operators
print(f"{num1} == {num2} (Equal to): {num1 == num2}")
print(f"{num1} != {num2} (Not equal to): {num1 != num2}")
print(f"{num1} > {num2} (Greater than): {num1 > num2}")
print(f"{num1} < {num2} (Less than): {num1 < num2}")
print(f"{num1} >= {num2} (Greater than or equal to): {num1 >= num2}")
print(f"{num1} <= {num2} (Less than or equal to): {num1 <= num2}")
